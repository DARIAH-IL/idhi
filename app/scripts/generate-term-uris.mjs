import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCHEMA_URL =
  'https://raw.githubusercontent.com/DARIAH-IL/idhi-manifests/refs/tags/v1.2.0/gen/idhi.schema.json'

const res = await fetch(SCHEMA_URL)
if (!res.ok) {
  throw new Error(`Failed to fetch schema: ${res.status}`)
}
const schema = await res.json()

const termUriOf = (node) => {
  if (!node || typeof node !== 'object') return undefined
  return node['x-termUri'] ?? termUriOf(node.items)
}

const refOf = (node) => {
  if (!node || typeof node !== 'object') return undefined
  const ref = node.$ref ?? node.items?.$ref
  return ref?.startsWith('#/$defs/') ? ref.slice('#/$defs/'.length) : undefined
}

const result = {}
const refs = {}
for (const [defName, def] of Object.entries(schema.$defs ?? {})) {
  const entry = {}
  const refEntry = {}
  const selfUri = def['x-termUri']
  if (selfUri) entry.$self = selfUri
  for (const [propName, prop] of Object.entries(def.properties ?? {})) {
    const uri = termUriOf(prop)
    if (uri) entry[propName] = uri
    const ref = refOf(prop)
    if (ref && schema.$defs[ref]?.properties) refEntry[propName] = ref
  }
  if (Object.keys(entry).length > 0) result[defName] = entry
  if (Object.keys(refEntry).length > 0) refs[defName] = refEntry
}

const outPath = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'api',
  'termUris',
  'termUris.ts',
)

const content = `/**
 * Generated by scripts/generate-term-uris.mjs from
 * ${SCHEMA_URL}
 * Do not edit manually.
 */
export const termUris = ${JSON.stringify(result, null, 2)} as const

export const termUriRefs = ${JSON.stringify(refs, null, 2)} as const
`

writeFileSync(outPath, content)
console.log(`Wrote ${outPath} (${Object.keys(result).length} entities)`)
